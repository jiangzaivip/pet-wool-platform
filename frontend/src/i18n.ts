function mergeMessages(target: Record<string, any>, source: Record<string, any>) {
  for (const [key, value] of Object.entries(source)) {
    if (value && typeof value === 'object' && !Array.isArray(value)) {
      target[key] = target[key] && typeof target[key] === 'object' ? target[key] : {}
      mergeMessages(target[key], value)
    } else {
      target[key] = value
    }
  }
}

for (const [language, overrides] of Object.entries(feedbackMessages)) {
  mergeMessages((messages as Record<string, any>)[language], overrides)
}

const supportedLanguages = ['ko', 'en', 'zh']

function detectLanguage() {
  try {
    const saved = localStorage.getItem('lang')
    if (saved && supportedLanguages.includes(saved)) return saved
  } catch {
    // Continue with the browser language when storage is unavailable.
  }
  return 'ko'
}

